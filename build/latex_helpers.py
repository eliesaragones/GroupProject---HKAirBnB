"""LaTeX twin of docx_helpers.py: the same function names, but the report is written as a .tex file.
make_report.py picks one of the two modules, so the Word and the LaTeX report always contain the same text and numbers."""
import re
from pathlib import Path

INK, GREY, BLUE = "ink", "grey", "blue"          # colour names defined in the preamble below

# characters that LaTeX must escape or that need a macro (works with pdfLaTeX and XeLaTeX/LuaLaTeX)
CHAR = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}", "×": r"$\times$", "÷": r"$\div$", "±": r"$\pm$", "≥": r"$\geq$", "≤": r"$\leq$", "≈": r"$\approx$", "→": r"$\rightarrow$",
        "←": r"$\leftarrow$", "−": r"$-$", "²": r"\textsuperscript{2}", "³": r"\textsuperscript{3}", "·": r"\textperiodcentered{}", "°": r"\textdegree{}",
        " ": "~", " ": "~", "–": "--", "—": "---", "…": r"\ldots{}", "‘": "`", "’": "'", "“": "``", "”": "''"}

def esc(text):
    """Plain text -> LaTeX (straight double quotes become typographic quotes)."""
    text = re.sub(r'"([^"]*)"', "“\\1”", str(text))
    return "".join(CHAR.get(c, c) for c in text)

def inline(text, code_size=None):
    """**bold**, *italic* and `code` markup -> LaTeX."""
    out = []
    for part in re.split(r"(\*\*.+?\*\*|`.+?`|\*[^*\s][^*]*?\*)", str(text)):
        if not part:
            continue
        if part.startswith("**"):
            out.append(r"\textbf{" + esc(part[2:-2]) + "}")
        elif part.startswith("`"):
            out.append(r"\texttt{" + esc(part[1:-1]) + "}")
        elif part.startswith("*"):
            out.append(r"\textit{" + esc(part[1:-1]) + "}")
        else:
            out.append(esc(part))
    return "".join(out)

class _Run:
    bold = False

class _Item:
    def __init__(self, kind, **kw):
        self.kind, self.kw, self.runs = kind, kw, [_Run()]

class Document:
    def __init__(self, body_pt, margins_cm):
        self.body_pt, self.margins_cm, self.footer, self.items = body_pt, margins_cm, "", []

    def add(self, kind, **kw):
        item = _Item(kind, **kw)
        self.items.append(item)
        return item

    # ---------------------------------------------------------------- rendering
    def preamble(self):
        m = self.margins_cm
        return r"""% Automatically generated by build/make_report.py --tex  (edit the Python script, not this file)
% Compile with:  xelatex Report.tex   (or pdflatex / lualatex; run it twice)
\documentclass[@PT@pt,a4paper]{article}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern}
\usepackage[a4paper,left=@M@cm,right=@M@cm,top=1.9cm,bottom=2.3cm]{geometry}
\usepackage{graphicx,array,colortbl,xcolor,microtype,fancyhdr,titlesec,enumitem,textcomp}
\usepackage[hidelinks]{hyperref}
\definecolor{ink}{HTML}{0B0B0B}
\definecolor{grey}{HTML}{52514E}
\definecolor{blue}{HTML}{1C5CAB}
\definecolor{hdr}{HTML}{1C5CAB}
\definecolor{hl}{HTML}{FCE9E1}
\definecolor{rule}{HTML}{E1E0D9}
\color{ink}
\setlength{\parindent}{0pt}
\setlength{\parskip}{4.5pt}
\linespread{1.04}
\setlength{\tabcolsep}{3pt}
\sloppy
\titleformat{\section}{\fontsize{13.5}{16}\bfseries\color{blue}}{}{0pt}{}
\titleformat{\subsection}{\fontsize{11}{13}\bfseries\color{ink}}{}{0pt}{}
\titlespacing*{\section}{0pt}{10pt}{3pt}
\titlespacing*{\subsection}{0pt}{7pt}{2pt}
\pagestyle{fancy}
\fancyhf{}
\renewcommand{\headrulewidth}{0pt}
\fancyfoot[C]{\footnotesize\color{grey}@FOOT@ \quad|\quad Page \thepage}
\begin{document}
""".replace("@PT@", str(self.body_pt)).replace("@M@", str(m)).replace("@FOOT@", esc(self.footer))

    def render(self):
        out, i, items = [self.preamble()], 0, self.items
        while i < len(items):
            it = items[i]
            if it.kind == "bullet":                      # consecutive bullets form one list
                out.append(r"\begin{itemize}[leftmargin=0.55cm,itemsep=2pt,topsep=2pt,parsep=0pt]")
                while i < len(items) and items[i].kind == "bullet":
                    out.append(r"\item " + inline(items[i].kw["text"]))
                    i += 1
                out.append(r"\end{itemize}")
                continue
            out.append(getattr(self, "_" + it.kind)(it))
            i += 1
        out.append(r"\end{document}")
        return "\n".join(out) + "\n"

    def _para(self, it):
        k = it.kw
        text = inline(k["text"])
        if it.runs[0].bold:
            text = r"\textbf{" + text + "}"
        size = k.get("size")
        head = (r"\fontsize{%s}{%s}\selectfont " % (size, round(size * 1.2, 1))) if size else ""
        if k.get("color"):
            head += r"\color{%s} " % k["color"]
        if k.get("italic"):
            head += r"\itshape "
        if k.get("align") != "justify":
            head += r"\raggedright "
        before = r"\vspace{%spt}" % k["before"] if k.get("before") else ""
        after = r"\vspace{%spt}" % (k["after"] - 4.5) if k.get("after") is not None and k["after"] != 4.5 else ""
        keep = r"\nopagebreak[4]" if k.get("keep_next") else ""
        return before + "{" + head + text + r"\par}" + after + keep

    def _heading(self, it):
        return "\\%s*{%s}" % ("section" if it.kw["level"] == 1 else "subsection", esc(it.kw["text"]))

    def _figure(self, it):
        k = it.kw
        cap = _Item("para", text=k["caption"], size=8.5, color="grey")
        return ("\\begin{center}\\nopagebreak\\includegraphics[width=%scm]{%s}\\end{center}\\vspace{-6pt}\\nopagebreak[4]\n" % (k["width"], k["path"])
                + self._para(cap) + r"\vspace{4pt}")

    def _table(self, it):
        k = it.kw
        rows, widths, size, align = k["rows"], k["widths"], k["size"], k["align"] or ["l"] * len(k["widths"])
        spec = "".join({"l": r">{\raggedright\arraybackslash}", "r": r">{\raggedleft\arraybackslash}", "c": r">{\centering\arraybackslash}"}[a]
                       + "p{%.2fcm}" % (w - 0.22) for a, w in zip(align, widths))
        lines = [r"\begin{center}{\fontsize{%s}{%s}\selectfont\arrayrulecolor{rule}" % (size, round(size * 1.2, 1)) + r"\begin{tabular}{" + spec + "}"]
        for i, row in enumerate(rows):
            cells = [inline(c) for c in row]
            if k["header"] and i == 0:
                lines.append(r"\rowcolor{hdr}" + " & ".join(r"\color{white}\bfseries " + c for c in cells) + r"\\")
            else:
                if i in k["highlight_rows"]:
                    lines.append(r"\rowcolor{hl}" + " & ".join(r"\bfseries " + c for c in cells) + r"\\\hline")
                elif k["bold_first_col"] and i > 0:
                    lines.append(r"\bfseries " + cells[0] + (" & " + " & ".join(cells[1:]) if len(cells) > 1 else "") + r"\\\hline")
                else:
                    lines.append(" & ".join(cells) + r"\\\hline")
        lines.append(r"\end{tabular}}\end{center}")
        return "\n".join(lines)

    def _page_break(self, it):
        return r"\newpage"

    def save(self, path):
        Path(path).write_text(self.render(), encoding="utf8")

def new_document(body_pt=10, margins_cm=2.0):
    return Document(body_pt, margins_cm)

def para(doc, text, size=None, align=None, after=None, before=None, color=None, italic=False, keep_next=False):
    return doc.add("para", text=text, size=size, align=align, after=after, before=before, color=color, italic=italic, keep_next=keep_next)

def bullet(doc, text, size=None, after=2):
    return doc.add("bullet", text=text)

def heading(doc, text, level=1):
    return doc.add("heading", text=text, level=level)

def figure(doc, path, width_cm, caption, note=None):
    rel = Path(path).resolve().relative_to(Path(__file__).resolve().parent.parent).as_posix()
    return doc.add("figure", path=rel, width=width_cm, caption=caption)

def table(doc, rows, col_widths_cm, header=True, size=8.5, align=None, bold_first_col=False, highlight_rows=()):
    return doc.add("table", rows=rows, widths=col_widths_cm, header=header, size=size, align=align, bold_first_col=bold_first_col,
                   highlight_rows=set(highlight_rows))

def page_break(doc):
    return doc.add("page_break")

def add_page_number_footer(doc, left_text):
    doc.footer = left_text
